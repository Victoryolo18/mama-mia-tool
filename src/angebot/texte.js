/** "Montag bis Donnerstag" oder "Montag, Mittwoch und Freitag" in der Sprache. */
export function wochentageInSprache(nummern, t) {
  const tage = [...nummern].sort((a, b) => a - b);
  const namen = tage.map((nr) => t.wochentage[nr - 1]);
  const lueckenlos = tage.length > 2 && tage.every((nr, i) => i === 0 || nr === tage[i - 1] + 1);
  return lueckenlos ? t.wochentagsSpanne(namen[0], namen.at(-1)) : t.wochentagsListe(namen);
}

/** Bedingungen des Firmen-Vorteils in der Sprache. Deutsch kommt aus firmenVorteil.js, damit es dort nur einmal steht. */
export function vorteilBedingungenInSprache(regel, t, deutsch) {
  return t.sprache === "de" ? deutsch(regel) : t.vorteilBedingungen(wochentageInSprache(regel.wochentage, t), regel.mindestpersonen);
}

/** Fehlermeldung zur Firma: Die Prüfung (firmenVorteil.js) spricht Deutsch, hier steht die Übersetzung.
    Unbekannte Meldungen (etwa mit Zahl) bleiben deutsch, damit nie eine leere Meldung erscheint. */
export function firmaFehlerInSprache(fehler, t) {
  return (fehler && t.firmaFehler[fehler]) || fehler;
}

/** Datum in der Sprache, wie im Generator angezeigt. */
export function datumInSprache(datum, t) {
  return datum ? new Date(datum).toLocaleDateString(t.locale, { day: "2-digit", month: "long", year: "numeric" }) : "—";
}
