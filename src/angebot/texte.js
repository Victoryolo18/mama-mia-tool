/** Russische Mehrzahl: 1 гость, 2 гостя, 5 гостей. */
export function ruZahl(n, [eins, wenige, viele]) {
  const z = Math.abs(n) % 100;
  const e = z % 10;
  if (z > 10 && z < 20) return viele;
  if (e === 1) return eins;
  if (e >= 2 && e <= 4) return wenige;
  return viele;
}

